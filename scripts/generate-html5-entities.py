#!/usr/bin/env python3
"""Generate the static HTML5 named-character-reference table used by port-links.mjs."""
from __future__ import annotations

import argparse
import json
from html.entities import html5
from pathlib import Path

OUT = Path(__file__).with_name("html5-entities.mjs")
HEADER = "// Generated by scripts/generate-html5-entities.py from Python's html.entities.html5. Do not edit.\n"


def content() -> str:
    # Preserve all HTML5 names, including legacy semicolonless aliases.
    entities = html5
    return HEADER + "export const HTML5_ENTITIES = " + json.dumps(entities, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + ";\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the checked-in table differs")
    args = parser.parse_args()
    expected = content()
    if args.check:
        return 0 if OUT.read_text(encoding="utf-8") == expected else 1
    OUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
